function ensureStars(w, h, seed) {
	if (stars && stars.length && stars[0].x < w && stars[0].y < h) return stars;
	stars = [];
	let s = seed || 1;
	const rand = () => {
		s = (s * 9301 + 49297) % 233280;
		return s / 233280;
	};
	const count = Math.floor(w * h / 12e3);
	for (let i = 0; i < count; i++) stars.push({
		x: rand() * w,
		y: rand() * h * .55,
		r: .4 + rand() * 1.2,
		p: rand() * Math.PI * 2
	});
	return stars;
}
function updateDust(w, h, wind, dt, now) {
	const spawnRate = 8 + Math.abs(wind) * 40;
	if (now - lastDustSpawn > 1e3 / spawnRate) {
		lastDustSpawn = now;
		const fromRight = wind < 0;
		dustParticles.push({
			x: fromRight ? w + 5 : -5,
			y: h * (.15 + Math.random() * .7),
			vx: wind * (30 + Math.random() * 40) + (Math.random() - .5) * 6,
			vy: (Math.random() - .5) * 12,
			life: 4 + Math.random() * 3,
			size: .6 + Math.random() * 1.4,
			alpha: .15 + Math.random() * .25
		});
	}
	for (const p of dustParticles) {
		p.x += p.vx * dt;
		p.y += p.vy * dt;
		p.life -= dt;
	}
	dustParticles = dustParticles.filter((p) => p.life > 0 && p.x > -20 && p.x < w + 20);
}
