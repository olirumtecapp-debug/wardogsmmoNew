function aiTakeTurn(state) {
	if (state.phase !== "aiming" || state.winner !== null) return;
	const me = state.dogs[state.currentPlayer];
	const enemy = state.dogs[1 - state.currentPlayer];
	if (!me || me.hp <= 0 || !enemy) return;
	me.facing = enemy.x > me.x ? 1 : -1;
	if (state.rageEnabled && !me.rageActive && me.rageCharge >= 60) activateRage(state);
	if (!me.shieldActive) {
		const hpRatio = me.hp / me.maxHp;
		const sosOk = hpRatio <= .35 && me.shieldCharge >= 25;
		const fullOk = me.shieldCharge >= 55;
		if (sosOk || fullOk && hpRatio < .65) activateShield(state);
	}
	const diff = getAIDifficulty();
	const dx = enemy.x - me.x;
	const absDx = Math.abs(dx);
	const moveChance = diff === "recruit" ? .35 : diff === "sergeant" ? .6 : .75;
	const jumpChance = diff === "recruit" ? .15 : diff === "sergeant" ? .25 : .35;
	if (!me.airborne && me.moveBudget > 8 && Math.random() < moveChance) {
		const idealMin = diff === "general" ? 220 : diff === "sergeant" ? 260 : 300;
		const idealMax = diff === "general" ? 380 : diff === "sergeant" ? 440 : 520;
		let dir = dx > 0 ? 1 : -1;
		let want = 0;
		if (absDx < idealMin) {
			dir = dx > 0 ? -1 : 1;
			want = idealMin - absDx;
		} else if (absDx > idealMax) {
			dir = dx > 0 ? 1 : -1;
			want = absDx - idealMax;
		}
		if (want > 12) {
			const cap = me.moveBudget * (diff === "recruit" ? .4 : diff === "sergeant" ? .6 : .8);
			const chunks = Math.max(1, Math.ceil(Math.min(want, cap) / 40));
			let done = 0;
			const walk = () => {
				if (state.phase !== "aiming" || done >= chunks) return;
				moveDog(state, dir, .12);
				done++;
				setTimeout(walk, 120);
			};
			walk();
		}
	}
	if (!me.hasJumped && !me.airborne && Math.random() < jumpChance) setTimeout(() => {
		if (state.phase === "aiming") jumpDog(state);
	}, 400);
	if (diff === "recruit") {
		const pool = [
			"bazooka",
			"grenade",
			"bow"
		].filter((w) => state.ammo[w] !== 0);
		state.weapon = pool.length ? pool[Math.floor(Math.random() * pool.length)] : "bazooka";
		const wildMiss = Math.random() < .35;
		state.angle = 15 + Math.random() * 65;
		state.power = 30 + Math.random() * 70;
		if (wildMiss) {
			state.angle = Math.random() < .5 ? 15 + Math.random() * 15 : 70 + Math.random() * 15;
			state.power = 30 + Math.random() * 30;
		}
		setTimeout(() => {
			if (state.phase === "aiming") fire(state);
		}, 900);
		return;
	}
	let candidates;
	if (diff === "general") {
		candidates = WEAPON_ORDER.filter((w) => state.ammo[w] !== 0);
		if (enemy.hp < 40) {
			const s = [
				"airstrike",
				"cluster",
				"artillery",
				"rpg"
			].filter((w) => state.ammo[w] !== 0);
			if (s.length) candidates = [...s, ...candidates.filter((w) => !s.includes(w))];
		}
	} else {
		candidates = [
			"bazooka",
			"grenade",
			"bow",
			"frag",
			"rpg"
		].filter((w) => state.ammo[w] !== 0);
		if (!candidates.length) candidates = ["bazooka"];
	}
	const angleStep = diff === "general" ? 3 : 8;
	const powerStep = diff === "general" ? 6 : 15;
	const angleMin = 15, angleMax = 82;
	const powerMin = 30, powerMax = diff === "general" ? 95 : 100;
	const maxWeapons = diff === "general" ? candidates.length : 2;
	const solutions = [];
	for (const wId of candidates.slice(0, maxWeapons)) for (let angle = angleMin; angle <= angleMax; angle += angleStep) for (let power = powerMin; power <= powerMax; power += powerStep) {
		const d = simulate(state, angle, power, wId);
		solutions.push({
			weapon: wId,
			angle,
			power,
			dist: d
		});
	}
	solutions.sort((a, b) => a.dist - b.dist);
	let pickIdx = 0;
	if (diff === "sergeant" && solutions.length > 3 && Math.random() < .25) pickIdx = 1 + Math.floor(Math.random() * 2);
	const best = solutions[pickIdx] ?? {
		weapon: candidates[0],
		angle: 45,
		power: 60,
		dist: Infinity
	};
	let jitterAng = diff === "general" ? 4 : 10;
	let jitterPow = diff === "general" ? 6 : 18;
	if (diff === "general" && Math.random() < .15) {
		jitterAng *= 2;
		jitterPow *= 2;
	}
	state.weapon = best.weapon;
	state.angle = Math.max(10, Math.min(85, best.angle + (Math.random() - .5) * jitterAng));
	state.power = Math.max(20, Math.min(100, best.power + (Math.random() - .5) * jitterPow));
	setTimeout(() => {
		if (state.phase === "aiming") fire(state);
	}, diff === "general" ? 1400 : 1100);
}
function simulate(state, angle, power, weaponId) {
	const w = WEAPONS[weaponId];
	const me = state.dogs[state.currentPlayer];
	const enemy = state.dogs[1 - state.currentPlayer];
	if (w.id === "airstrike") {
		const targetX = me.x + me.facing * (power * 3.5);
		return Math.abs(targetX - enemy.x);
	}
	const rad = angle * Math.PI / 180;
	const dir = me.facing;
	const v = power * w.speed * .6;
	let vx = Math.cos(rad) * v * dir;
	let vy = -Math.sin(rad) * v;
	let x = me.x + dir * 18, y = me.y - 6;
	const dt = 1 / 60;
	const gravity = 500 * w.gravityScale;
	const wind = state.wind;
	const width = state.width, height = state.height;
	const diff = getAIDifficulty();
	for (let i = 0; i < 600; i++) {
		if (w.affectedByWind) vx += wind * 40 * dt;
		if (w.id === "rpg" && i * dt < 1.4) {
			const sp = Math.hypot(vx, vy) || 1;
			vx += vx / sp * 260 * dt;
			vy += vy / sp * 260 * dt;
		}
		vy += gravity * dt;
		x += vx * dt;
		y += vy * dt;
		if (x < 0 || x > width || y > height) break;
		if (isSolid(state, x, y)) {
			let dist = Math.hypot(x - enemy.x, y - (enemy.y - 8));
			if (Math.hypot(x - me.x, y - me.y) < 40) dist += diff === "general" ? 800 : diff === "sergeant" ? 260 : 120;
			return dist;
		}
	}
	return Math.hypot(x - enemy.x, y - (enemy.y - 8));
}
function isSolid(state, x, y) {
	if (x < 0 || x >= state.width || y < 0 || y >= state.height) return false;
	return state.terrain[Math.floor(y) * state.width + Math.floor(x)] === 1;
}
