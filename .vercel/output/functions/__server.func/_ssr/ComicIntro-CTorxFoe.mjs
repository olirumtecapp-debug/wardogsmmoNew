function ensureBarricadeCanvas(b) {
	if (b._canvas && !b._dirty) return;
	const c = b._canvas ?? document.createElement("canvas");
	c.width = b.w0;
	c.height = b.h0;
	const cx = c.getContext("2d");
	if (!cx) return;
	cx.clearRect(0, 0, c.width, c.height);
	const sprite = barricadeImgs[b.kind];
	if (sprite && sprite.complete && sprite.naturalWidth > 0) {
		cx.imageSmoothingEnabled = true;
		cx.imageSmoothingQuality = "high";
		cx.drawImage(sprite, 0, 0, b.w0, b.h0);
	} else {
		drawBarricadePattern(cx, b.kind, b.w0, b.h0);
		if (sprite) b._dirty = true;
	}
	const img = cx.getImageData(0, 0, c.width, c.height);
	const data = img.data;
	const mask = b.mask;
	for (let i = 0; i < mask.length; i++) if (!mask[i]) data[i * 4 + 3] = 0;
	cx.putImageData(img, 0, 0);
	b._canvas = c;
	if (!(sprite && !(sprite.complete && sprite.naturalWidth > 0))) b._dirty = false;
}
