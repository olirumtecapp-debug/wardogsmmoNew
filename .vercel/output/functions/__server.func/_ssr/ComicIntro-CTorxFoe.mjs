	sfxBark(t0, mul, variant) {
		const ctx = this.ctx;
		const cfg = [
			{
				base: 240,
				formant: 950,
				dur: .16,
				second: .1
			},
			{
				base: 175,
				formant: 720,
				dur: .2,
				second: .12
			},
			{
				base: 300,
				formant: 1150,
				dur: .13,
				second: .08
			},
			{
				base: 210,
				formant: 880,
				dur: .14,
				second: .09
			}
		][variant % 4];
		const wof = (start, freqMul, vol) => {
			const o1 = ctx.createOscillator();
			const o2 = ctx.createOscillator();
			o1.type = "sawtooth";
			o2.type = "square";
			const f = cfg.base * freqMul * (.97 + Math.random() * .06);
			o1.frequency.setValueAtTime(f * .55, start);
			o1.frequency.exponentialRampToValueAtTime(f, start + .02);
			o1.frequency.exponentialRampToValueAtTime(f * .55, start + cfg.dur);
			o2.frequency.setValueAtTime(f * 1.5, start);
			o2.frequency.exponentialRampToValueAtTime(f * .8, start + cfg.dur);
			const bp = ctx.createBiquadFilter();
			bp.type = "bandpass";
			bp.frequency.setValueAtTime(cfg.formant * .7, start);
			bp.frequency.linearRampToValueAtTime(cfg.formant, start + cfg.dur * .4);
			bp.frequency.linearRampToValueAtTime(cfg.formant * .75, start + cfg.dur);
			bp.Q.value = 1.2;
			const lp = ctx.createBiquadFilter();
			lp.type = "lowpass";
			lp.frequency.value = 2600;
			const src = ctx.createGain();
			const g1 = ctx.createGain();
			g1.gain.value = .8;
			const g2 = ctx.createGain();
			g2.gain.value = .5;
			o1.connect(g1).connect(src);
			o2.connect(g2).connect(src);
			const filtered = ctx.createGain();
			filtered.gain.value = .65;
			const dry = ctx.createGain();
			dry.gain.value = .45;
			src.connect(bp).connect(lp).connect(filtered);
			src.connect(dry);
			const eg = ctx.createGain();
			eg.gain.setValueAtTime(1e-4, start);
			eg.gain.exponentialRampToValueAtTime(Math.max(1e-4, vol * mul), start + .008);
			eg.gain.exponentialRampToValueAtTime(1e-4, start + cfg.dur);
			filtered.connect(eg);
			dry.connect(eg);
			eg.connect(this.sfxDryGain);
			o1.start(start);
			o2.start(start);
			o1.stop(start + cfg.dur + .05);
			o2.stop(start + cfg.dur + .05);
		};
		wof(t0, 1, .9);
		wof(t0 + cfg.second, .88, .7);
	}
