function drawHpBar(ctx, x, y, hp, maxHp, color, dark) {
	const segCount = 8, segW = 2;
	const totalW = 20.2;
	const barH = 2.4;
	const startX = x - totalW / 2;
	ctx.save();
	ctx.fillStyle = "rgba(0,0,0,0.5)";
	roundRect(ctx, startX - 2, y - 1.5, 24.2, 5.4, 2);
	ctx.fill();
	const pct = Math.max(0, Math.min(1, hp / Math.max(1, maxHp)));
	const filled = Math.round(pct * segCount);
	const pulse = pct < .3 ? .6 + .4 * Math.abs(Math.sin(performance.now() * .008)) : 1;
	for (let i = 0; i < segCount; i++) {
		const sx = startX + i * 2.6;
		if (i < filled) {
			const g = ctx.createLinearGradient(0, y, 0, y + barH);
			g.addColorStop(0, color);
			g.addColorStop(1, dark);
			ctx.fillStyle = g;
			ctx.globalAlpha = pulse;
			ctx.fillRect(sx, y, segW, barH);
			ctx.globalAlpha = 1;
		} else {
			ctx.fillStyle = "rgba(255,255,255,0.06)";
			ctx.fillRect(sx, y, segW, barH);
		}
	}
	ctx.fillStyle = "#fff";
	ctx.font = "bold 7px Chakra Petch, sans-serif";
	ctx.textAlign = "center";
	ctx.shadowColor = "rgba(0,0,0,0.85)";
	ctx.shadowBlur = 2;
	ctx.fillText(`${hp}`, x, y - 3);
	ctx.textAlign = "start";
	ctx.restore();
}
