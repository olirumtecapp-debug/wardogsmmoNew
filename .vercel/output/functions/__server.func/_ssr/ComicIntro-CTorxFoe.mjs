function barricadeAt(state, x, y) {
	const xi = Math.floor(x), yi = Math.floor(y);
	for (const b of state.barricades) {
		const lx = xi - b.x0, ly = yi - b.y0;
		if (lx < 0 || ly < 0 || lx >= b.w0 || ly >= b.h0) continue;
		if (!b.mask[ly * b.w0 + lx]) continue;
		let solid = 0;
		for (const [ox, oy] of [
			[-2, 0],
			[2, 0],
			[0, -2],
			[0, 2]
		]) {
			const nx = lx + ox, ny = ly + oy;
			if (nx < 0 || ny < 0 || nx >= b.w0 || ny >= b.h0) continue;
			if (b.mask[ny * b.w0 + nx]) solid++;
		}
		if (solid >= 2) return b;
	}
	return null;
}
function barricadeTopAt(state, x, y, tol = 2) {
	const xi = Math.floor(x);
	for (const b of state.barricades) {
		const lx = xi - b.x0;
		if (lx < 0 || lx >= b.w0) continue;
		for (let dy = -tol; dy <= 2; dy++) {
			const ly = Math.floor(y - b.y0) + dy;
			if (ly < 0 || ly >= b.h0) continue;
			if (b.mask[ly * b.w0 + lx]) {
				if (ly === 0 || !b.mask[(ly - 1) * b.w0 + lx]) return b;
				break;
			}
		}
	}
	return null;
}
